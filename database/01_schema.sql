IF DB_ID(N'DemoAplikasiDB') IS NULL CREATE DATABASE DemoAplikasiDB;
GO
USE DemoAplikasiDB;
GO
IF OBJECT_ID(N'dbo.AppUsers',N'U') IS NULL
BEGIN
 CREATE TABLE dbo.AppUsers (
  Id INT IDENTITY PRIMARY KEY, Username NVARCHAR(80) NOT NULL UNIQUE,
  FullName NVARCHAR(150) NOT NULL, Email NVARCHAR(180) NULL,
  PasswordHash NVARCHAR(600) NOT NULL, RoleName VARCHAR(12) NOT NULL,
  IsActive BIT NOT NULL CONSTRAINT DF_AppUsers_Active DEFAULT(1),
  CreatedAt DATETIMEOFFSET(0) NOT NULL CONSTRAINT DF_AppUsers_Created DEFAULT(SYSDATETIMEOFFSET()),
  CONSTRAINT CK_AppUsers_Role CHECK(RoleName IN ('MAHASISWA','DOSEN','PIC'))
 );
END
GO
IF OBJECT_ID(N'dbo.DemoPeriod',N'U') IS NULL
BEGIN
 CREATE TABLE dbo.DemoPeriod (
  Id INT NOT NULL PRIMARY KEY CHECK(Id=1), IsOpen BIT NOT NULL,
  StartAt DATETIMEOFFSET(0) NOT NULL, EndAt DATETIMEOFFSET(0) NOT NULL,
  RequirementsText NVARCHAR(1500) NULL,
  UpdatedAt DATETIMEOFFSET(0) NOT NULL DEFAULT(SYSDATETIMEOFFSET()),
  CONSTRAINT CK_DemoPeriod_Dates CHECK(EndAt>StartAt)
 );
END
GO
IF OBJECT_ID(N'dbo.DemoRequests',N'U') IS NULL
BEGIN
 CREATE TABLE dbo.DemoRequests (
  Id INT IDENTITY PRIMARY KEY,
  StudentId INT NOT NULL REFERENCES dbo.AppUsers(Id),
  LecturerId INT NOT NULL REFERENCES dbo.AppUsers(Id),
  Title NVARCHAR(180) NOT NULL, Description NVARCHAR(2000) NOT NULL DEFAULT(N''),
  ScheduledAt DATETIMEOFFSET(0) NULL,
  DurationMinutes INT NULL,
  Location NVARCHAR(150) NULL,
  RequiredDocuments NVARCHAR(1500) NOT NULL,
  Status VARCHAR(28) NOT NULL DEFAULT('PENDING_PIC'),
  ReviewNotes NVARCHAR(1500) NULL,
  LecturerReviewNotes NVARCHAR(1500) NULL,
  LecturerNotes NVARCHAR(1500) NULL,
  LecturerScore INT NULL,
  SubmissionNotes NVARCHAR(1500) NULL,
  CreatedAt DATETIMEOFFSET(0) NOT NULL DEFAULT(SYSDATETIMEOFFSET()),
  UpdatedAt DATETIMEOFFSET(0) NOT NULL DEFAULT(SYSDATETIMEOFFSET()),
  CONSTRAINT CK_DemoRequests_Duration CHECK(DurationMinutes IS NULL OR DurationMinutes BETWEEN 15 AND 240),
  CONSTRAINT CK_DemoRequests_Score CHECK(LecturerScore IS NULL OR LecturerScore BETWEEN 0 AND 100),
  CONSTRAINT CK_DemoRequests_Status CHECK(Status IN (
   'PENDING_PIC','REVISION_PIC','PENDING_DOSEN','REVISION_DOSEN',
   'READY_TO_SCHEDULE','SCHEDULED','DEMO_DONE','SUBMITTED',
   'SUBMISSION_REVISION','COMPLETED','REJECTED','CANCELLED'))
 );
 CREATE INDEX IX_Demo_Student ON dbo.DemoRequests(StudentId,CreatedAt DESC);
 CREATE INDEX IX_Demo_Lecturer ON dbo.DemoRequests(LecturerId,Status,ScheduledAt);
 CREATE INDEX IX_Demo_Schedule ON dbo.DemoRequests(Status,ScheduledAt);
END
GO
IF OBJECT_ID(N'dbo.DemoFiles',N'U') IS NULL
BEGIN
 CREATE TABLE dbo.DemoFiles (
  Id INT IDENTITY PRIMARY KEY, DemoId INT NOT NULL REFERENCES dbo.DemoRequests(Id),
  UploadedBy INT NOT NULL REFERENCES dbo.AppUsers(Id),
  FileKind VARCHAR(12) NOT NULL CHECK(FileKind IN ('SUPPORTING','SUBMISSION')),
  OriginalName NVARCHAR(255) NOT NULL, StoredName VARCHAR(100) NOT NULL UNIQUE,
  ContentType VARCHAR(100) NOT NULL, FileSize BIGINT NOT NULL CHECK(FileSize>0),
  CreatedAt DATETIMEOFFSET(0) NOT NULL DEFAULT(SYSDATETIMEOFFSET())
 );
 CREATE INDEX IX_Files_Demo ON dbo.DemoFiles(DemoId,CreatedAt DESC);
END
GO
IF OBJECT_ID(N'dbo.DemoHistory',N'U') IS NULL
BEGIN
 CREATE TABLE dbo.DemoHistory (
  Id INT IDENTITY PRIMARY KEY,DemoId INT NOT NULL REFERENCES dbo.DemoRequests(Id),
  ActorId INT NOT NULL REFERENCES dbo.AppUsers(Id), ActionName NVARCHAR(80) NOT NULL,
  FromStatus VARCHAR(28) NULL,ToStatus VARCHAR(28) NOT NULL,
  Notes NVARCHAR(1500) NULL,CreatedAt DATETIMEOFFSET(0) NOT NULL DEFAULT(SYSDATETIMEOFFSET())
 );
 CREATE INDEX IX_History_Demo ON dbo.DemoHistory(DemoId,CreatedAt DESC);
END
GO
IF OBJECT_ID(N'dbo.DemoNotifications',N'U') IS NULL
BEGIN
 CREATE TABLE dbo.DemoNotifications (
  Id INT IDENTITY PRIMARY KEY,DemoId INT NOT NULL REFERENCES dbo.DemoRequests(Id),
  UserId INT NOT NULL REFERENCES dbo.AppUsers(Id),
  Title NVARCHAR(140) NOT NULL, Message NVARCHAR(600) NOT NULL,
  IsRead BIT NOT NULL DEFAULT(0),
  CreatedAt DATETIMEOFFSET(0) NOT NULL DEFAULT(SYSDATETIMEOFFSET())
 );
 CREATE INDEX IX_Notif_User ON dbo.DemoNotifications(UserId,IsRead,CreatedAt DESC);
END
GO
